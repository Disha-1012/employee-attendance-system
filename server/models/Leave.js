import mongoose from "mongoose";


/*
|--------------------------------------------------------------------------
| Leave Schema
|--------------------------------------------------------------------------
*/

const leaveSchema =
  new mongoose.Schema(
    {

      /*
      |--------------------------------------------------------------------------
      | Employee
      |--------------------------------------------------------------------------
      */

      employee: {
        type: mongoose.Schema.Types.ObjectId,
        ref: "User",
        required: true,
        index: true
      },


      /*
      |--------------------------------------------------------------------------
      | Employee ID
      |--------------------------------------------------------------------------
      |
      | Stored separately so that employee ID remains
      | available even when the User document changes.
      |--------------------------------------------------------------------------
      */

      employeeId: {
        type: String,
        required: true,
        index: true
      },


      /*
      |--------------------------------------------------------------------------
      | Leave Type
      |--------------------------------------------------------------------------
      */

      leaveType: {
        type: String,
        enum: [
          "paid",
          "unpaid"
        ],
        default: "paid",
        required: true
      },


      /*
      |--------------------------------------------------------------------------
      | Start Date
      |--------------------------------------------------------------------------
      */

      startDate: {
        type: String,
        required: true
      },


      /*
      |--------------------------------------------------------------------------
      | End Date
      |--------------------------------------------------------------------------
      */

      endDate: {
        type: String,
        required: true
      },


      /*
      |--------------------------------------------------------------------------
      | Total Leave Days
      |--------------------------------------------------------------------------
      */

      totalDays: {
        type: Number,
        required: true,
        min: 1
      },


      /*
      |--------------------------------------------------------------------------
      | Reason
      |--------------------------------------------------------------------------
      */

      reason: {
        type: String,
        required: true,
        trim: true,
        maxlength: 500
      },


      /*
      |--------------------------------------------------------------------------
      | Leave Status
      |--------------------------------------------------------------------------
      */

      status: {
        type: String,
        enum: [
          "pending",
          "approved",
          "rejected",
          "cancelled"
        ],
        default: "pending",
        index: true
      },


      /*
      |--------------------------------------------------------------------------
      | HR Reviewer
      |--------------------------------------------------------------------------
      */

      reviewedBy: {
        type: mongoose.Schema.Types.ObjectId,
        ref: "User",
        default: null
      },


      /*
      |--------------------------------------------------------------------------
      | Review Date
      |--------------------------------------------------------------------------
      */

      reviewedAt: {
        type: Date,
        default: null
      },


      /*
      |--------------------------------------------------------------------------
      | Rejection Reason
      |--------------------------------------------------------------------------
      */

      rejectionReason: {
        type: String,
        trim: true,
        maxlength: 500,
        default: ""
      }

    },

    {
      timestamps: true
    }
  );


/*
|--------------------------------------------------------------------------
| Indexes
|--------------------------------------------------------------------------
|
| Helps prevent unnecessary duplicate/overlapping queries.
|--------------------------------------------------------------------------
*/

leaveSchema.index({
  employee: 1,
  startDate: 1,
  endDate: 1
});


leaveSchema.index({
  status: 1,
  createdAt: -1
});


const Leave =
  mongoose.model(
    "Leave",
    leaveSchema
  );


export default Leave;
